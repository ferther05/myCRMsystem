    KEY idx_customer_team_status (team_id, customer_status, sea_type),
    KEY idx_customer_recycle (sea_type, customer_status, warning_at),
    KEY idx_customer_prev_owner (previous_owner_id, return_priority_until),
    CONSTRAINT fk_customer_owner FOREIGN KEY (owner_id) REFERENCES sys_user (id) ON DELETE SET NULL ON UPDATE RESTRICT,
    CONSTRAINT fk_customer_team FOREIGN KEY (team_id) REFERENCES sys_team (id) ON DELETE SET NULL ON UPDATE RESTRICT,
    CONSTRAINT fk_customer_previous_owner FOREIGN KEY (previous_owner_id) REFERENCES sys_user (id) ON DELETE SET NULL ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='客户主档';

