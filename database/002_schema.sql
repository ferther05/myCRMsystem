    CONSTRAINT fk_contract_customer FOREIGN KEY (customer_id) REFERENCES crm_customer (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_contract_opportunity FOREIGN KEY (opportunity_id) REFERENCES crm_opportunity (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_contract_owner FOREIGN KEY (owner_id) REFERENCES sys_user (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_contract_team FOREIGN KEY (team_id) REFERENCES sys_team (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_contract_performance_owner FOREIGN KEY (performance_owner_id) REFERENCES sys_user (id) ON DELETE SET NULL ON UPDATE RESTRICT,
    CONSTRAINT fk_contract_performance_team FOREIGN KEY (performance_team_id) REFERENCES sys_team (id) ON DELETE SET NULL ON UPDATE RESTRICT,
    CONSTRAINT ck_contract_amounts CHECK (contract_amount >= 0 AND received_amount >= 0 AND outstanding_amount >= 0 AND received_amount <= contract_amount)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='合同';

