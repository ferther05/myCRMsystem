USE crm_system;

SET NAMES utf8mb4;
SET time_zone = '+08:00';
SET FOREIGN_KEY_CHECKS = 0;

CREATE TABLE IF NOT EXISTS sys_team (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    team_code VARCHAR(32) NOT NULL,
    team_name VARCHAR(100) NOT NULL,
    manager_id BIGINT UNSIGNED NULL,
    enabled TINYINT(1) NOT NULL DEFAULT 1,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_team_code (team_code),
    UNIQUE KEY uk_team_name (team_name),
    KEY idx_team_manager (manager_id),
    CONSTRAINT ck_team_enabled CHECK (enabled IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='销售团队';

CREATE TABLE IF NOT EXISTS sys_user (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    username VARCHAR(64) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    real_name VARCHAR(80) NOT NULL,
    phone VARCHAR(32) NULL,
    email VARCHAR(160) NULL,
    role_code VARCHAR(20) NOT NULL,
    team_id BIGINT UNSIGNED NULL,
    account_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    must_change_password TINYINT(1) NOT NULL DEFAULT 1,
    claim_date DATE NULL,
    claim_count INT UNSIGNED NOT NULL DEFAULT 0,
    current_hold_count INT UNSIGNED NOT NULL DEFAULT 0,
    last_login_at DATETIME(3) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_by BIGINT UNSIGNED NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_user_username (username),
    UNIQUE KEY uk_user_email (email),
    KEY idx_user_team_status (team_id, account_status),
    KEY idx_user_role_status (role_code, account_status),
    CONSTRAINT ck_user_role CHECK (role_code IN ('ADMIN', 'MANAGER', 'SPECIALIST')),
    CONSTRAINT ck_user_status CHECK (account_status IN ('PENDING', 'ACTIVE', 'DISABLED')),
    CONSTRAINT ck_user_change_password CHECK (must_change_password IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='系统用户';

ALTER TABLE sys_user
    ADD CONSTRAINT fk_user_team FOREIGN KEY (team_id) REFERENCES sys_team (id) ON DELETE RESTRICT ON UPDATE RESTRICT;

ALTER TABLE sys_team
    ADD CONSTRAINT fk_team_manager FOREIGN KEY (manager_id) REFERENCES sys_user (id) ON DELETE SET NULL ON UPDATE RESTRICT;

