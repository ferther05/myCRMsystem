import { http } from './http'

export const listCustomers = (params) => http.get('/customers', { params })
export const getCustomer = (id) => http.get(`/customers/${id}`)
export const createCustomer = (payload) => http.post('/customers', payload)
export const editCustomer = (id, payload) => http.put(`/customers/${id}`, payload)
export const classifyCustomer = (id, payload) => http.patch(`/customers/${id}/classification`, payload)
export const deleteCustomer = (id, version) => http.delete(`/customers/${id}`, { params: { version } })
export const listCustomerOwners = () => http.get('/customers/owners')
export const addContact = (id, payload) => http.post(`/customers/${id}/contacts`, payload)
export const editContact = (id, contactId, payload) => http.put(`/customers/${id}/contacts/${contactId}`, payload)
export const deleteContact = (id, contactId, customerVersion) => http.delete(`/customers/${id}/contacts/${contactId}`, { params: { customerVersion } })
export const addFollowRecord = (id, payload) => http.post(`/customers/${id}/follow-records`, payload)
export const reviewFollowRecord = (id, followId, payload) => http.patch(`/customers/${id}/follow-records/${followId}/review`, payload)
export const claimCustomer = (id, version) => http.post(`/customers/${id}/claim?version=${version}`)
export const transferCustomer = (id, payload) => http.patch(`/customers/${id}/ownership`, payload)
export const listCustomerDictionaries = () => http.get('/customer-dictionaries')
export const createCustomerDictionary = (payload) => http.post('/customer-dictionaries', payload)
export const editCustomerDictionary = (id, payload) => http.put(`/customer-dictionaries/${id}`, payload)
